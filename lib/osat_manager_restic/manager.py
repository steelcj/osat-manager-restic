"""The manager contract for restic: install, switch, aliases, protection,
the verified archive, removal, self-install and uninstall.

What the manager owns, under its install root:

    versions/<version>/restic         installed binaries, read-only
    versions/<version>/provenance.json
    archive/<version>/                verified downloads, kept for offline restore
    manager/                          the manager itself, after --self-install
    state.json                        the active version and the alias names

and, in its alias directory, only the launchers it wrote. It never
touches restic's own configuration, cache, repositories or passwords.
"""

from __future__ import annotations

import bz2
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable, Dict, List, Optional, Tuple

from . import __version__
from .errors import ManagerError
from .net import Network, NotPublished
from .openpgp import verify
from .platforms import Paths, protect, remove_tree, unprotect

VERSION = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")
ALIAS_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]{0,63}$")
MARKER = "Generated by manage-restic"
DEFAULT, SELF = "default", "self"
SMALL_FILE = 1024 * 1024        # SHA256SUMS and its signature are a few KiB

Runner = Callable[[List[str]], str]


def run_binary(argv: List[str]) -> str:
    result = subprocess.run(argv, capture_output=True, text=True, timeout=60)
    if result.returncode != 0:
        raise ManagerError(f"{argv[0]} exited with {result.returncode}: "
                           f"{result.stderr.strip()}")
    return result.stdout


def version_key(version: str) -> Tuple[int, int, int]:
    match = VERSION.match(version)
    if not match:
        raise ManagerError(f"{version!r} is not a version such as 0.19.1")
    return tuple(int(p) for p in match.groups())


def minor_of(version: str) -> str:
    major, minor, _ = version_key(version)
    return f"{major}.{minor}"


class Manager:
    def __init__(self, manifest: dict, paths: Paths, system: str, arch: str,
                 net: Optional[Network] = None,
                 runner: Runner = run_binary, log=print):
        self.manifest, self.paths = manifest, paths
        self.system, self.arch = system, arch
        self.net = net or Network()
        self.runner, self.log = runner, log
        self.created: List[str] = []

    def make_dir(self, path: Path) -> None:
        """mkdir -p, remembering every directory outside the install root
        that did not exist, so uninstall can remove them if left empty."""
        missing = [p for p in [path, *path.parents] if not p.exists()]
        path.mkdir(parents=True, exist_ok=True)
        root = self.paths.root
        for p in missing:
            if p != root and root not in p.parents:
                self.created.append(str(p))

    # ── State ────────────────────────────────────────────────────────────

    def read_state(self) -> dict:
        if not self.paths.state.is_file():
            return {"format": 1, "active": None, "aliases": {}}
        return json.loads(self.paths.state.read_text(encoding="utf-8"))

    def write_state(self, state: dict) -> None:
        self.make_dir(self.paths.root)
        created = state.setdefault("created_dirs", [])
        for path in self.created:
            if path not in created:
                created.append(path)
        self.created = []
        tmp = self.paths.state.with_suffix(".tmp")
        tmp.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
        os.replace(tmp, self.paths.state)

    def installed(self) -> List[str]:
        if not self.paths.versions.is_dir():
            return []
        found = [p.name for p in self.paths.versions.iterdir()
                 if VERSION.match(p.name) and
                 self.paths.binary(p.name).is_file()]
        return sorted(found, key=version_key)

    def archived(self) -> List[str]:
        if not self.paths.archive.is_dir():
            return []
        return sorted((p.name for p in self.paths.archive.iterdir()
                       if VERSION.match(p.name)), key=version_key)

    # ── Acquisition and verification ─────────────────────────────────────

    def asset_name(self, version: str) -> str:
        template = self.manifest["sources"]["assets"][self.system]
        return template.format(version=version, arch=self.arch)

    def url(self, version: str, name: str) -> str:
        return self.manifest["sources"]["release_url"].format(
            version=version, file=name)

    def verify_files(self, sums: bytes, signature: str, asset_name: str,
                     asset: bytes) -> str:
        """Check the signature on SHA256SUMS with the pinned key, then the
        asset's SHA-256 against it. Return the asset's SHA-256."""
        key = self.manifest["verification"]["signing_key"]
        verify(sums, signature, key["public_key"], key["fingerprint"])
        expected = None
        for line in sums.decode("utf-8").splitlines():
            parts = line.split()
            if len(parts) == 2 and parts[1].lstrip("*") == asset_name:
                expected = parts[0].lower()
        if expected is None:
            raise ManagerError(f"{asset_name} is not listed in the signed "
                               f"SHA256SUMS")
        actual = hashlib.sha256(asset).hexdigest()
        if actual != expected:
            raise ManagerError(f"{asset_name}: SHA-256 {actual} does not "
                               f"match the signed {expected}")
        return actual

    def acquire(self, version: str) -> Tuple[bytes, str, str]:
        """The verified asset for a version: from the archive when it holds
        one, with no network request, otherwise downloaded, verified and
        archived. Returns (asset bytes, sha256, source)."""
        name = self.asset_name(version)
        sums_name = self.manifest["sources"]["checksums"]
        sig_name = self.manifest["sources"]["signature"]
        archive = self.paths.archive / version
        if (archive / name).is_file():
            sums = (archive / sums_name).read_bytes()
            try:
                sig = (archive / sig_name).read_bytes().decode("ascii")
            except UnicodeDecodeError:
                raise ManagerError(f"the archived {sig_name} for {version} "
                                   f"is not an ASCII-armored signature") from None
            asset = (archive / name).read_bytes()
            sha = self.verify_files(sums, sig, name, asset)
            self.log(f"[manage-restic] restoring {name} from the verified "
                     f"archive, signature and checksum re-checked")
            return asset, sha, "archive"

        try:
            sums = self.net.fetch(self.url(version, sums_name),
                                  max_bytes=SMALL_FILE)
        except NotPublished:
            raise ManagerError(f"restic {version} was never published "
                               f"(no {sums_name} for v{version})") from None
        try:
            sig = self.net.fetch(self.url(version, sig_name),
                                 max_bytes=SMALL_FILE).decode("ascii")
        except UnicodeDecodeError:
            raise ManagerError(f"{sig_name} for v{version} is not an "
                               f"ASCII-armored signature") from None
        try:
            asset = self.net.fetch(self.url(version, name))
        except NotPublished:
            raise ManagerError(f"restic {version} was published, but not "
                               f"as {name} for {self.system}/{self.arch}") from None
        sha = self.verify_files(sums, sig, name, asset)
        if self.manifest["verification"].get("keep_verified_archive", True):
            unprotect(archive)
            archive.mkdir(parents=True, exist_ok=True)
            (archive / sums_name).write_bytes(sums)
            (archive / sig_name).write_bytes(sig.encode("utf-8"))
            (archive / name).write_bytes(asset)
            protect(archive)
        return asset, sha, self.url(version, name)

    def extract(self, asset_name: str, asset: bytes, target: Path) -> None:
        if asset_name.endswith(".bz2"):
            target.write_bytes(bz2.decompress(asset))
        elif asset_name.endswith(".zip"):
            import io
            with zipfile.ZipFile(io.BytesIO(asset)) as archive:
                members = [m for m in archive.namelist()
                           if m.endswith(".exe") and "/" not in m]
                if len(members) != 1:
                    raise ManagerError(f"{asset_name} does not hold exactly "
                                       f"one executable")
                target.write_bytes(archive.read(members[0]))
        else:
            raise ManagerError(f"unknown asset format: {asset_name}")
        if not self.paths.windows:
            target.chmod(0o700)

    def health_check(self, binary: Path, version: str) -> None:
        output = self.runner([str(binary), "version"])
        if not re.search(rf"\brestic {re.escape(version)}\b", output):
            raise ManagerError(f"the binary reports {output.strip()!r}, not "
                               f"restic {version}; it was not installed")

    # ── Commands ─────────────────────────────────────────────────────────

    def install(self, version: Optional[str] = None) -> str:
        if version is None:
            version = self.net.latest_version(
                self.manifest["sources"]["latest_release_api"])
            self.log(f"[manage-restic] latest restic release: {version}")
        version_key(version)
        self.make_dir(self.paths.root)
        if version in self.installed():
            self.log(f"[manage-restic] restic {version} is already installed")
            return self.switch(version)
        asset, sha, source = self.acquire(version)
        staging = self.paths.staging / version
        remove_tree(staging)
        staging.mkdir(parents=True)
        try:
            binary = staging / self.paths.binary(version).name
            self.extract(self.asset_name(version), asset, binary)
            self.health_check(binary, version)
            key = self.manifest["verification"]["signing_key"]["fingerprint"]
            (staging / "provenance.json").write_text(json.dumps({
                "version": version,
                "asset": self.asset_name(version),
                "sha256": sha,
                "signed_by": key,
                "source": source,
                "installed_at": datetime.now(timezone.utc).strftime(
                    "%Y-%m-%dT%H:%M:%SZ"),
                "installed_by": f"manage-restic {__version__}",
            }, indent=2) + "\n", encoding="utf-8")
            target = self.paths.versions / version
            self.paths.versions.mkdir(parents=True, exist_ok=True)
            os.replace(staging, target)
            protect(target)
        finally:
            remove_tree(staging)
            if self.paths.staging.is_dir() and not any(self.paths.staging.iterdir()):
                self.paths.staging.rmdir()
        self.log(f"[manage-restic] installed restic {version}, verified "
                 f"against the signed SHA256SUMS")
        return self.switch(version)

    def switch(self, version: str) -> str:
        if version not in self.installed():
            raise ManagerError(f"restic {version} is not installed")
        state = self.read_state()
        state["active"] = version
        self.write_aliases(state)
        self.log(f"[manage-restic] restic {version} is now active")
        return version

    def remove(self, version: str) -> None:
        state = self.read_state()
        if version not in self.installed():
            raise ManagerError(f"restic {version} is not installed")
        if state.get("active") == version:
            raise ManagerError(f"restic {version} is active; switch to "
                               f"another version first")
        remove_tree(self.paths.versions / version)
        self.write_aliases(state)
        self.log(f"[manage-restic] removed restic {version}; its verified "
                 f"archive is kept")

    def rename_alias(self, spec: str) -> None:
        if spec.count("=") != 1:
            raise ManagerError("give the rename as OLD=NEW")
        old, new = spec.split("=")
        if not ALIAS_NAME.match(new):
            raise ManagerError(f"{new!r} is not a valid alias name")
        state = self.read_state()
        slots = state.setdefault("aliases", {})
        slot = next((s for s, n in slots.items() if n == old), None)
        if slot is None:
            raise ManagerError(f"no alias named {old!r}")
        if new in slots.values():
            raise ManagerError(f"an alias named {new!r} already exists")
        target = self.paths.launcher(new)
        if target.exists() and not self.owns(target):
            raise ManagerError(f"{target} exists and was not written by "
                               f"manage-restic")
        self.remove_launcher(old)
        slots[slot] = new
        self.write_aliases(state)
        self.log(f"[manage-restic] alias {old} is now {new}")

    # ── Aliases ──────────────────────────────────────────────────────────

    def owns(self, path: Path) -> bool:
        try:
            return MARKER in path.read_text(encoding="utf-8")[:300]
        except (OSError, UnicodeDecodeError):
            return False

    def remove_launcher(self, name: str) -> None:
        path = self.paths.launcher(name)
        if path.exists() and self.owns(path):
            path.unlink()

    def launcher_text(self, command: List[str], env: Optional[Dict[str, str]] = None) -> str:
        env = env or {}
        if self.paths.windows:
            lines = ["@echo off", f"rem {MARKER}; do not edit.", "setlocal"]
            lines += [f'set "{k}={v}"' for k, v in env.items()]
            lines.append(" ".join(f'"{c}"' for c in command) + " %*")
            return "\r\n".join(lines) + "\r\n"
        lines = ["#!/bin/sh", f"# {MARKER}; do not edit."]
        lines += [f"{k}='{v}'; export {k}" for k, v in env.items()]
        lines.append("exec " + " ".join(f"'{c}'" for c in command) + ' "$@"')
        return "\n".join(lines) + "\n"

    def write_launcher(self, name: str, text: str) -> None:
        path = self.paths.launcher(name)
        if path.exists() and not self.owns(path):
            raise ManagerError(f"{path} exists and was not written by "
                               f"manage-restic; it is left alone")
        self.make_dir(self.paths.bin_dir)
        with path.open("w", encoding="utf-8", newline="") as f:
            f.write(text)
        if not self.paths.windows:
            path.chmod(0o700)

    def write_aliases(self, state: dict) -> None:
        """Rewrite every alias from the state: the generic alias for the
        active version, one alias per installed minor line, and the
        manager itself once self-installed."""
        installed = self.installed()
        slots: Dict[str, str] = state.setdefault("aliases", {})
        active = state.get("active")
        if active not in installed:
            active = state["active"] = None
        targets: Dict[str, str] = {}
        if active:
            targets[DEFAULT] = active
        for version in installed:
            line = minor_of(version)
            if active and minor_of(active) == line:
                targets[line] = active
            elif line not in targets or version_key(version) > version_key(targets[line]):
                targets[line] = version
        template = self.manifest["versions"]["versioned_alias"]
        for slot in list(slots):
            if slot not in targets and slot != SELF:
                self.remove_launcher(slots.pop(slot))
        for slot, version in targets.items():
            if slot not in slots:
                if slot == DEFAULT:
                    slots[slot] = self.manifest["versions"]["default_alias"]
                else:
                    major, minor = slot.split(".")
                    slots[slot] = template.format(major=major, minor=minor)
            self.write_launcher(slots[slot],
                                self.launcher_text([str(self.paths.binary(version))]))
        self.write_state(state)

    # ── Status ───────────────────────────────────────────────────────────

    def status(self) -> str:
        state = self.read_state()
        lines = [f"manage-restic {__version__}",
                 f"install root  {self.paths.root}",
                 f"aliases in    {self.paths.bin_dir}",
                 f"active        {state.get('active') or 'none'}",
                 f"installed     {', '.join(self.installed()) or 'none'}",
                 f"archived      {', '.join(self.archived()) or 'none'}"]
        for slot, name in sorted(state.get("aliases", {}).items()):
            lines.append(f"alias         {name}  ({slot})")
        return "\n".join(lines)

    # ── The manager itself ───────────────────────────────────────────────

    def self_install(self, manifest_file: Path) -> Path:
        """Copy the manager into its install root and write a
        manage-restic launcher, so it works from any directory."""
        package = Path(__file__).resolve().parent
        self.make_dir(self.paths.root)
        target = self.paths.manager / package.name
        remove_tree(self.paths.manager)
        shutil.copytree(package, target,
                        ignore=shutil.ignore_patterns("__pycache__"))
        (target / "data").mkdir(exist_ok=True)
        shutil.copyfile(manifest_file, target / "data" / "manager.yaml")
        (target / "VERSION").write_text(__version__ + "\n", encoding="utf-8")
        state = self.read_state()
        slots = state.setdefault("aliases", {})
        slots.setdefault(SELF, self.manifest["tool"]["command"])
        self.write_launcher(slots[SELF], self.launcher_text(
            [sys.executable, "-m", package.name],
            {"PYTHONPATH": str(self.paths.manager)}))
        self.write_state(state)
        protect(self.paths.manager)
        self.log(f"[manage-restic] installed manage-restic {__version__} "
                 f"into {self.paths.manager}")
        return target

    def uninstall(self) -> None:
        """Remove everything the manager owns: versions, archive, state,
        the manager itself and its launchers."""
        state = self.read_state()
        for name in state.get("aliases", {}).values():
            self.remove_launcher(name)
        remove_tree(self.paths.root)
        for path in sorted(state.get("created_dirs", []), key=len, reverse=True):
            directory = Path(path)
            if directory.is_dir() and not any(directory.iterdir()):
                directory.rmdir()
        self.log(f"[manage-restic] removed {self.paths.root} and every "
                 f"launcher manage-restic wrote; restic's own configuration "
                 f"and repositories are untouched")
